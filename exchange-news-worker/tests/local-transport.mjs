import assert from 'node:assert/strict';
import { forwardOutbound, singleFlightReader } from '../local-transport.mjs';
const controller = new AbortController();
let received;
const waiting = (_url, options) => new Promise((resolve, reject) => {
  received = options.signal;
  options.signal.addEventListener('abort', () => reject(options.signal.reason), { once: true });
});
const pending = forwardOutbound(new Request('https://example.invalid', { signal: controller.signal }), waiting);
controller.abort(new Error('upstream cancelled'));
await assert.rejects(pending, /upstream cancelled/);
assert.equal(received.aborted, true);
const keepAlive = setTimeout(() => {}, 1000);
await assert.rejects(forwardOutbound(new Request('https://example.invalid'), waiting, 10), /timeout/i);
clearTimeout(keepAlive);
let calls = 0, release;
const read = singleFlightReader(() => { calls++; return new Promise(resolve => { release = resolve; }); }, 15);
await Promise.all([assert.rejects(read(), /超时/), assert.rejects(read(), /超时/)]);
assert.equal(calls, 1);
await assert.rejects(read(), /超时/);
assert.equal(calls, 1);
release({ ok: true });
await new Promise(resolve => setImmediate(resolve));
const next = read();
await new Promise(resolve => setImmediate(resolve));
release({ ok: true });
assert.deepEqual(await next, { ok: true });
assert.equal(calls, 2);
console.log('PASS: cancellation propagation, hard deadline, single flight across timeouts, recovery');
